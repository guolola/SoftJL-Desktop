// Positive source fixtures must cover their explicit associations as well as their business nodes.
export function createUseCaseRelationshipTrace(model: Pick<UseCaseDiagramSpec, "relationships" | "modelId">, ruleId = "r1"): RequirementModelTraceabilityEntry[] {
  return model.relationships.map((edge) => ({ ruleId, target: { diagramKind: "usecase", modelId: model.modelId,
    elementId: edge.id, elementKind: "relationship", label: `${edge.sourceId} → ${edge.targetId}` } }));
}

